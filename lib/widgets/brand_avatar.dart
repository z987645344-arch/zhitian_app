/// 品牌头像标记：琥珀外框 + 浅色内圆、人物居中的 OC 头像图标，替代原先的圆形"知"字。
///
/// 图标以 base64 内嵌（256px WebP，约 11KB），不新增 pubspec 资源声明。
class BrandAvatar extends StatelessWidget {
  const BrandAvatar({super.key, required this.size});

  final double size;

  static final Uint8List _bytes = base64Decode(_avatarWebp);

  @override
  Widget build(BuildContext context) {
    // 图标自带外框与内圆，这里只做圆角裁切和光晕。
    return Container(
      width: size,
      height: size,
      decoration: BoxDecoration(
        borderRadius: BorderRadius.circular(size * 0.225),
        boxShadow: [
          BoxShadow(
            color: AppColors.primary.withValues(alpha: 0.4),
            blurRadius: size * 0.5,
          ),
        ],
      ),
      child: ClipRRect(
        borderRadius: BorderRadius.circular(size * 0.225),
        child: Image.memory(
          _bytes,
          width: size,
          height: size,
          fit: BoxFit.cover,
          gaplessPlayback: true,
          excludeFromSemantics: true,
        ),
      ),
    );
  }
}

class BrandSilhouette extends StatelessWidget {
  const BrandSilhouette({super.key, required this.size, required this.color});

  final double size;
  final Color color;

  static final Uint8List _bytes = base64Decode(_silhouettePng);

  @override
  Widget build(BuildContext context) {
    return Image.memory(
      _bytes,
      width: size,
      height: size,
      fit: BoxFit.contain,
      color: color,
      colorBlendMode: BlendMode.srcIn,
      gaplessPlayback: true,
      excludeFromSemantics: true,
    );
  }
}

